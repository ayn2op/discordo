//go:build ignore

package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"strings"
)

const (
	baseURL = "https://discord.com"
	appURL  = baseURL + "/app"
	// parseCall precedes the JavaScript string literal that holds the emoji JSON.
	parseCall = `JSON.parse('`
)

var bundleRegex = regexp.MustCompile(`/assets/vnd-emoji\.[0-9a-f]+\.js`)

type emoji struct {
	Names      []string `json:"names"`
	Surrogates string   `json:"surrogates"`
}

func get(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("failed to fetch %s; status=%q", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// unquote returns the JavaScript string literal at the start of s as JSON.
func unquote(s string) (string, error) {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '\'':
			return b.String(), nil
		case '\\':
			i++
			if i == len(s) {
				return "", errors.New("unterminated escape")
			}

			switch s[i] {
			case 'x':
				// JSON has no \x escape, but \u00 is the same code point.
				b.WriteString(`\u00`)
			case '\'':
				b.WriteByte('\'')
			default:
				// The other escapes mean the same in JSON.
				b.WriteByte('\\')
				b.WriteByte(s[i])
			}
		default:
			b.WriteByte(s[i])
		}
	}

	return "", errors.New("unterminated string")
}

func fetchEmojis() ([]emoji, error) {
	app, err := get(appURL)
	if err != nil {
		return nil, err
	}

	path := bundleRegex.Find(app)
	if path == nil {
		return nil, errors.New("failed to find emoji bundle")
	}

	bundle, err := get(baseURL + string(path))
	if err != nil {
		return nil, err
	}

	i := bytes.Index(bundle, []byte(parseCall+`{"emojis":[`))
	if i == -1 {
		return nil, errors.New("failed to find emoji JSON")
	}

	data, err := unquote(string(bundle[i+len(parseCall):]))
	if err != nil {
		return nil, err
	}

	var v struct {
		Emojis []emoji `json:"emojis"`
	}
	if err := json.Unmarshal([]byte(data), &v); err != nil {
		return nil, err
	}

	if len(v.Emojis) == 0 {
		return nil, errors.New("no emojis")
	}
	return v.Emojis, nil
}

func main() {
	emojis, err := fetchEmojis()
	if err != nil {
		panic(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage discordemoji\n\nvar entries = [...]entry{\n")
	for _, e := range emojis {
		for _, name := range e.Names {
			fmt.Fprintf(&b, "{%q, %q},\n", name, e.Surrogates)
		}
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}

	if err := os.WriteFile("generated.go", src, 0644); err != nil {
		panic(err)
	}
}
