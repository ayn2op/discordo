//go:build ignore

// Command generator writes docs/config.md from the config structs: a heading per table and option, named by its toml key, with its doc comment and default value.
package main

import (
	"bytes"
	"encoding"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/BurntSushi/toml"
	"github.com/ayn2op/discordo/internal/config"
)

const header = "<!-- GENERATED BY go generate; DO NOT EDIT. -->\n\n"

// docs maps "Type.Field" to the doc comment of that struct field.
var docs = map[string]string{}

type field struct {
	key, doc string
	value    reflect.Value
}

// structFields returns the fields of the struct value, with those of embedded structs in place.
func structFields(value reflect.Value) []field {
	var fields []field
	structType := value.Type()
	for index := range structType.NumField() {
		structField := structType.Field(index)
		if structField.Anonymous {
			fields = append(fields, structFields(value.Field(index))...)
			continue
		}

		fields = append(fields, field{structField.Tag.Get("toml"), docs[structType.Name()+"."+structField.Name], value.Field(index)})
	}

	return fields
}

// isTable reports whether value is written as a table rather than as a value.
func isTable(value reflect.Value) bool {
	switch value.Interface().(type) {
	case toml.Marshaler, encoding.TextMarshaler:
		return false
	}

	return value.Kind() == reflect.Struct
}

// write writes a section for each option of the table at path: its doc comment, then its default value or, for a table, its own options.
func write(buffer *bytes.Buffer, path string, table reflect.Value) {
	if path != "" {
		path += "."
	}

	for _, field := range structFields(table) {
		name := path + field.key
		fmt.Fprintf(buffer, "%s %s\n\n", strings.Repeat("#", strings.Count(name, ".")+1), name)
		if field.doc != "" {
			fmt.Fprintf(buffer, "%s\n", field.doc)
		}

		if isTable(field.value) {
			write(buffer, name, field.value)
			continue
		}

		fmt.Fprintf(buffer, "Default: `%s`\n\n", encodeValue(field))
	}
}

// encodeValue returns the TOML of field's value. The encoder only writes whole documents, so the value is what follows the key.
func encodeValue(field field) string {
	var line bytes.Buffer
	if err := toml.NewEncoder(&line).Encode(map[string]any{field.key: field.value.Interface()}); err != nil {
		log.Fatal(err)
	}

	_, value, _ := strings.Cut(line.String(), " = ")
	return strings.TrimSpace(value)
}

// collectDocs adds the doc comment of each struct field in file to docs.
func collectDocs(file *ast.File) {
	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.TypeSpec)
		if !ok {
			return true
		}

		structType, ok := spec.Type.(*ast.StructType)
		if !ok {
			return false
		}

		addFieldDocs(spec.Name.Name, structType)
		return false
	})
}

func addFieldDocs(typeName string, structType *ast.StructType) {
	for _, field := range structType.Fields.List {
		for _, name := range field.Names {
			docs[typeName+"."+name.Name] = field.Doc.Text()
		}
	}
}

func main() {
	names, _ := filepath.Glob("*.go")
	for _, name := range names {
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, parser.ParseComments)
		if err != nil {
			log.Fatal(err)
		}

		collectDocs(file)
	}

	buffer := bytes.NewBufferString(header)
	write(buffer, "", reflect.ValueOf(config.Default()))
	if err := os.WriteFile("../../docs/config.md", append(bytes.TrimSpace(buffer.Bytes()), '\n'), 0o644); err != nil {
		log.Fatal(err)
	}
}
